"""
run_all.py -- regenerate every result, plot and table with one command:

    python run_all.py

Outputs go to results/. Everything is deterministic (no random numbers), so
running it twice gives identical numbers. Takes ~20 s on a laptop.
Exits with status 1 if any sanity check fails.
"""

import csv
import os
import sys
import time

import analysis
import device as dev
import network1d
import plots
import sanity
import transient

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")


def path(name):
    """Absolute path of an output file."""
    return os.path.join(OUT, name)


def write_tables(results, nets, gaps, runs, burst, conv_rows, extrap):
    """CSV of the variants plus a markdown summary used by the README."""
    keys = list(results)
    with open(path("variants.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["key", "variant", "T_junction_C", "T_surface_peak_C", "T_top_peak_C",
                    "T_skin_peak_C", "bracket_dT_K", "bracket_growth_um", "bracket_rotation_urad",
                    "sustainable_power_W", "added_mass_g", "Q_top_W", "Q_ends_W", "Q_fins_W",
                    "Q_body_W"])
        for k in keys:
            r, m, e = results[k], results[k]["m"], results[k]["exp"]
            w.writerow([k, r["variant"].label, f"{m['T_junction']:.2f}", f"{m['T_surface_peak']:.2f}",
                        f"{m['T_top_peak']:.2f}", f"{m['T_skin_peak']:.2f}", f"{e['dT_max']:.3f}",
                        f"{e['dL_um']:.2f}", f"{e['rotation_urad']:.3f}", f"{r['p_max']:.3f}",
                        f"{r['mass']:.2f}", f"{m['Q_top']:.3f}", f"{m['Q_ends']:.3f}",
                        f"{m['Q_fins']:.3f}", f"{m['Q_skin']:.3f}"])

    L = ["# Results summary (generated by run_all.py)", "",
         f"Conditions: {dev.POWER} W SoC, {dev.T_AMBIENT:.0f} C room, sealed "
         f"{dev.LENGTH / dev.MM:.0f} x {dev.DEPTH / dev.MM:.0f} x {dev.HEIGHT / dev.MM:.0f} mm enclosure "
         "unless noted. Limit: 43 C on any outer surface.", "",
         "## Design variants", "",
         "| Variant | Junction (C) | Peak surface (C) | Skin side peak (C) | Meets 43 C? | "
         "Bracket dT (K) | Bracket growth (um) | Sustainable power (W) | Added mass (g) |",
         "|---|---|---|---|---|---|---|---|---|"]
    for k in keys:
        r, m, e = results[k], results[k]["m"], results[k]["exp"]
        ok = "yes" if m["T_surface_peak"] <= dev.SKIN_LIMIT else "no"
        L.append(f"| {r['variant'].label} | {m['T_junction']:.1f} | {m['T_surface_peak']:.1f} | "
                 f"{m['T_skin_peak']:.1f} | {ok} | {e['dT_max']:.2f} | {e['dL_um']:.1f} | "
                 f"{r['p_max']:.2f} | {r['mass']:.1f} |")
    L += ["", "## Closing the gap to 3.5 W continuous", "",
          "| Option | Junction (C) | Top peak (C) | Skin side peak (C) | Bracket dT (K) | "
          "Sustainable power (W) | Added mass (g) |", "|---|---|---|---|---|---|---|"]
    for g in gaps:
        L.append(f"| {g['option']} | {g['T_junction']:.1f} | {g['T_top_peak']:.1f} | "
                 f"{g['T_skin_peak']:.1f} | {g['bracket_dT']:.2f} | {g['p_max']:.2f} | {g['mass']:.1f} |")
    L += ["", "## Transient warm-up at 3.5 W", "",
          "| Variant | t63 surface (min) | t95 surface (min) | Time to 43 C surface (min) |",
          "|---|---|---|---|"]
    for k, r in runs.items():
        L.append(f"| {dev.variant_by_key(k).label} | "
                 f"{transient.time_to_fraction(r.t, r.T_surface, 0.632) / 60:.1f} | "
                 f"{transient.time_to_fraction(r.t, r.T_surface, 0.95) / 60:.1f} | {burst[k] / 60:.1f} |")
    L += ["", "## Bracket (camera-IMU) detail", "",
          "| Variant | dT ends (K) | dT through thickness (K) | Axial growth (um) | "
          "Rotation, free mount (urad / arcsec) | Rotation if bonded to PCB (mrad) |",
          "|---|---|---|---|---|---|"]
    for k in keys:
        e = results[k]["exp"]
        L.append(f"| {results[k]['variant'].label} | {e['dT_ends']:.2f} | {e['dT_through']:.4f} | "
                 f"{e['dL_um']:.1f} | {e['rotation_urad']:.2f} / {e['rotation_arcsec']:.2f} | "
                 f"{e['bonded_rotation_urad'] / 1e3:.2f} |")
    L += ["", "## 1D network vs 2D solver", "",
          "| Variant | Junction net/2D (C) | Top surface net/2D (C) | PCB net/2D (C) | Skin side net/2D (C) |",
          "|---|---|---|---|---|"]
    for k in keys:
        n, m = nets[k].T, results[k]["m"]
        L.append(f"| {k} | {n['J']:.1f} / {m['T_die_mean']:.1f} | {n['To']:.1f} / {m['T_top_mean']:.1f} | "
                 f"{n['P']:.1f} / {m['T_pcb_mean']:.1f} | {n['Bo']:.1f} / {m['T_skin_mean']:.1f} |")
    L += ["", "## Grid convergence (baseline)", "",
          "| Refinement | Cells | Junction (C) | Peak surface (C) |", "|---|---|---|---|"]
    for row in conv_rows:
        L.append(f"| {row[0]:g}x | {int(row[1])} | {row[2]:.3f} | {row[3]:.3f} |")
    L.append(f"| Richardson extrapolation | - | {extrap[0]:.3f} | {extrap[1]:.3f} |")
    with open(path("summary.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    return "\n".join(L)


def main():
    """Run every model, study, plot and check."""
    os.makedirs(OUT, exist_ok=True)
    t0 = time.time()
    best = dev.RECOMMENDED_KEY
    print("Solving design variants (steady state + sustainable power)...")
    results = analysis.run_variants()
    print("Solving 1D resistance networks...")
    nets = {k: network1d.solve_network(r["variant"]) for k, r in results.items()}
    print("Spreader thickness sweep...")
    sweep = analysis.spreader_sweep()
    print("Grid convergence study...")
    conv_rows = analysis.grid_convergence(dev.VARIANTS[0])
    extrap = [analysis.richardson(*conv_rows[1:, c])[1] for c in (2, 3)]
    print("Transient warm-up runs...")
    runs = {k: transient.run_warmup(dev.variant_by_key(k)) for k in ("a", best)}
    burst = {k: transient.time_to(r.t, r.T_surface, dev.SKIN_LIMIT) for k, r in runs.items()}
    print("Options to close the gap to 3.5 W...")
    gaps = analysis.gap_closers()

    print("Plotting...")
    plots.plot_schematic(path("01_stackup_schematic.png"), dev.variant_by_key(best))
    plots.plot_network(path("02_resistance_network_baseline.png"), nets["a"],
                       results["a"]["variant"], results["a"]["sol"])
    plots.plot_network(path("02b_resistance_network_recommended.png"), nets[best],
                       results[best]["variant"], results[best]["sol"])
    plots.plot_contours(path("03_contours_baseline_vs_best.png"), results["a"]["sol"],
                        results[best]["sol"])
    plots.plot_flux(path("04_heat_flux_best.png"), results[best]["sol"])
    plots.plot_variants(path("05_variant_comparison.png"), results)
    plots.plot_sweep(path("06_spreader_sweep.png"), sweep)
    plots.plot_transient(path("07_transient_warmup.png"), runs, burst)
    plots.plot_bracket(path("08_bracket_expansion.png"), results, ["a", best])
    plots.plot_convergence(path("09_grid_convergence.png"), conv_rows, extrap)

    print("Sanity checks...")
    checks = (sanity.check_energy(results) + sanity.check_transient(runs, results)
              + sanity.check_grid(conv_rows, analysis.richardson)
              + sanity.check_network(nets, results) + sanity.check_physics(results, sweep))
    text, passed = sanity.report(checks)
    with open(path("sanity_checks.txt"), "w") as fh:
        fh.write(text + "\n")

    summary = write_tables(results, nets, gaps, runs, burst, conv_rows, extrap)
    print("\n" + summary)
    print("\n" + text)
    print(f"\nDone in {time.time() - t0:.0f} s. Outputs in {OUT}")
    return 0 if passed else 1


if __name__ == "__main__":
    sys.exit(main())
